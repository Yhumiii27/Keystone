// Formats in the database (Norma 1.2 §4, R-N02): every column carries its constraint — the domain of a state, the shape of a
// code, a name that is not blank, a value in its range, columns that agree. The application keeps its own checks for a clear
// message; the database refuses what slipped through. Relative imports only: drizzle-kit loads the schema files directly.
//
// `oneOf` / `allOf` take the column's own TypeScript type (`$type<…>()`, usually a union of src/server/db/codes.ts): the list
// must hold every value of the type and nothing else, checked at compile time — a value added to the type without its list
// (then `npm run db:generate`) fails `npm run typecheck`, and src/server/db/formats.test.ts compares the lists with the CHECKs
// of a migrated database. A CHECK lets NULL through: `notNull()` says whether a column may be empty.
import { sql, type SQL } from 'drizzle-orm';
import { check, type PgColumn } from 'drizzle-orm/pg-core';

/** `unknown` when `V` covers `T`, else an object that names the values missing from the list. */
type Covers<T, V> = [Exclude<T, V>] extends [never] ? unknown : { missingValues: Exclude<T, V> };

const lit = (v: string | number) => (typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`);

/** Every domain CHECK of the schema (constraint name → values, in order), compared with a migrated database by formats.test.ts. */
export const DOMAIN_CHECKS = new Map<string, readonly (string | number)[]>();

function register(name: string, values: readonly (string | number)[]) {
  if (name.length > 63) throw new Error(`Constraint name longer than 63 characters: ${name}`);
  DOMAIN_CHECKS.set(name, values);
}

/**
 * The column takes one of the values of its type `T` (NULL passes): `oneOf<ClaimStatus>()('…_domain', t.status, [...])`. The
 * columns the table callback receives carry no TypeScript type, hence the type named again.
 */
export const oneOf =
  <T extends string | number>() =>
  <const V extends readonly T[]>(name: string, col: PgColumn, values: V & Covers<T, V[number]>) => {
    const list = values as readonly (string | number)[];
    register(name, list);
    return check(name, sql`${col} in (${sql.raw(list.map(lit).join(', '))})`);
  };

/** Every element of a text array column is one of the values of `T` (NULL passes). */
export const allOf =
  <T extends string>() =>
  <const V extends readonly T[]>(name: string, col: PgColumn, values: V & Covers<T, V[number]>) => {
    const list = values as readonly string[];
    register(name, list);
    return check(name, sql`${col} <@ array[${sql.raw(list.map(lit).join(', '))}]::text[]`);
  };

/** A name, a title or a code that is not blank. */
export const filled = (name: string, col: PgColumn) => check(name, sql`length(btrim(${col})) > 0`);

/** The text matches a POSIX regular expression (a code generated by Keystone, an ISO code). */
export const shaped = (name: string, col: PgColumn, re: string) => check(name, sql`${col} ~ ${sql.raw(lit(re))}`);

/** lo ≤ col ≤ hi; a null bound is no bound. */
export function within(name: string, col: PgColumn, lo: number | null, hi: number | null) {
  if (lo != null && hi != null) return check(name, sql`${col} between ${sql.raw(String(lo))} and ${sql.raw(String(hi))}`);
  if (lo != null) return check(name, sql`${col} >= ${sql.raw(String(lo))}`);
  if (hi != null) return check(name, sql`${col} <= ${sql.raw(String(hi))}`);
  throw new Error(`${name}: no bound`);
}

/** The end is not before the start (either may be null). */
export const ordered = (name: string, start: PgColumn, end: PgColumn) => check(name, sql`${end} >= ${start}`);

/** Any other rule between columns. */
export const rule = (name: string, expr: SQL) => check(name, expr);

// ── Shapes ───────────────────────────────────────────────────────────────────────────────────────────────────────────
/** ISO 4217 currency, ISO 3166 alpha-2 country, three-letter client / subsidiary code. */
export const CURRENCY_RE = '^[A-Z]{3}$';
export const COUNTRY_RE = '^[A-Z]{2}$';
export const CODE3_RE = '^[A-Z]{3}$';
/** "PREFIX-nnn" business number (src/server/db/codes.ts nextBusinessNumber: zero-padded to `pad` digits, more when it grows). */
export const numbered = (prefix: string, pad: number) => `^${prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[0-9]{${pad},}$`;
