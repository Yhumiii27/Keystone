import 'server-only';
// PDF writer (chapter 4 exports, C-5): sober branded A4 documents — "Keystone", the title, the project and the date in the
// header, "Page x / y" in the footer — built from blocks (headings, paragraphs, fields, KPI tiles, tables with repeated
// headers, signature boxes). pdfkit (MIT) with the standard Helvetica fonts: text is mapped to the WinAnsi set they cover
// (French accents, €, «», ’, …) and the few other characters to close equivalents. Runs in Node only (next.config.ts).
import PDFDocument from 'pdfkit';
import type { Lang } from '@/i18n/translate';
import { displayCell, formatDate, isNumericType } from './format';
import type { CellValue, ExportColumn, PdfBlock, PdfDocument } from './types';

const INK = '#1d1d1f';
const MUTED = '#6b6b70';
const RULE = '#d0d0d4';
const FILL = '#f2f2f4';
const ACCENT = '#3a3a8c';
const FONT = 'Helvetica';
const BOLD = 'Helvetica-Bold';

/** Characters of the Windows-1252 set the standard fonts can draw, beyond Latin-1. */
const CP1252_EXTRA = new Set('€‚ƒ„…†‡ˆ‰Š‹ŒŽ‘’“”•–—˜™š›œžŸ');
const REPLACE: Record<string, string> = {
  '−': '-', '‐': '-', '‑': '-', '→': '->', '←': '<-', '↔': '<->', '≥': '>=', '≤': '<=', '≠': '!=',
  ' ': ' ', ' ': ' ', ' ': ' ', ' ': ' ', '…': '…', '✓': 'v', '✔': 'v', '✗': 'x', '·': '·',
  '′': "'", '″': '"', '­': '', '​': '', '≈': '~', '×': '×', '●': '•', '○': 'o',
};

/** Text the standard PDF fonts can render (WinAnsi), with close replacements for the rest. */
export function pdfText(s: string): string {
  let out = '';
  for (const ch of s.normalize('NFC')) {
    const code = ch.codePointAt(0)!;
    if (REPLACE[ch] !== undefined) out += REPLACE[ch];
    else if ((code >= 0x20 && code <= 0x7e) || (code >= 0xa0 && code <= 0xff) || CP1252_EXTRA.has(ch) || ch === '\n') out += ch;
    else {
      const base = ch.normalize('NFD').replace(/[̀-ͯ]/g, '');
      out += base && base !== ch && [...base].every((c) => c.charCodeAt(0) < 0x100) ? base : '?';
    }
  }
  return out;
}

export interface PdfLabels {
  /** "Page" — the footer reads "Page 2 / 5". */
  page: string;
  /** "Exported on" (header date line prefix is the document date; this is for the footer's export stamp). */
  generated: string;
}

const LABELS: Record<Lang, PdfLabels> = {
  en: { page: 'Page', generated: 'Generated by Keystone on' },
  fr: { page: 'Page', generated: 'Généré par Keystone le' },
};

type Doc = PDFKit.PDFDocument;

/** Renders a document to PDF bytes. `lang` drives number and date formats and the footer; `compress: false` keeps the content streams readable (tests). */
export async function renderPdf(spec: PdfDocument, lang: Lang, now: Date = new Date(), opts: { compress?: boolean } = {}): Promise<Uint8Array> {
  const doc: Doc = new PDFDocument({
    compress: opts.compress ?? true,
    size: 'A4', layout: spec.landscape ? 'landscape' : 'portrait', margins: { top: 42, bottom: 54, left: 42, right: 42 }, bufferPages: true,
    info: { Title: pdfText(spec.title), Author: 'Keystone', Creator: 'Keystone', Producer: 'Keystone' },
  });
  const chunks: Buffer[] = [];
  doc.on('data', (c: Buffer) => chunks.push(c));
  const done = new Promise<void>((resolve, reject) => {
    doc.on('end', () => resolve());
    doc.on('error', reject);
  });

  header(doc, spec, lang);
  for (const b of spec.blocks) block(doc, b, lang);
  if (spec.footnote) {
    ensure(doc, 30);
    doc.moveDown(0.8).font(FONT).fontSize(7.5).fillColor(MUTED).text(pdfText(spec.footnote), { width: contentWidth(doc) });
  }
  footers(doc, spec, lang, now);
  doc.end();
  await done;
  return new Uint8Array(Buffer.concat(chunks));
}

const contentWidth = (doc: Doc) => doc.page.width - doc.page.margins.left - doc.page.margins.right;
const bottom = (doc: Doc) => doc.page.height - doc.page.margins.bottom;

function ensure(doc: Doc, h: number): void {
  if (doc.y + h > bottom(doc)) doc.addPage();
}

function header(doc: Doc, spec: PdfDocument, lang: Lang): void {
  const x = doc.page.margins.left;
  const w = contentWidth(doc);
  const top = doc.page.margins.top;
  doc.font(BOLD).fontSize(10).fillColor(ACCENT).text('KEYSTONE', x, top, { characterSpacing: 2, lineBreak: false });
  if (spec.reference) doc.font(BOLD).fontSize(10).fillColor(INK).text(pdfText(spec.reference), x, top, { width: w, align: 'right' });
  doc.font(BOLD).fontSize(17).fillColor(INK).text(pdfText(spec.title), x, top + 20, { width: w });
  if (spec.subtitle) doc.font(FONT).fontSize(10).fillColor(MUTED).text(pdfText(spec.subtitle), { width: w });
  const meta = [spec.project ? `${spec.project.code} · ${spec.project.name}` : null, formatDate(spec.date ?? new Date().toISOString().slice(0, 10), lang)].filter(Boolean).join('  ·  ');
  doc.moveDown(0.2).font(FONT).fontSize(9).fillColor(MUTED).text(pdfText(meta), { width: w });
  const y = doc.y + 6;
  doc.moveTo(x, y).lineTo(x + w, y).lineWidth(0.8).strokeColor(RULE).stroke();
  doc.y = y + 12;
  doc.x = x;
}

function footers(doc: Doc, spec: PdfDocument, lang: Lang, now: Date): void {
  const range = doc.bufferedPageRange();
  const l = LABELS[lang];
  const stamp = `${l.generated} ${formatDate(now.toISOString(), lang, true)}`;
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    const keepBottom = doc.page.margins.bottom;
    doc.page.margins.bottom = 0;
    const x = doc.page.margins.left;
    const w = contentWidth(doc);
    const y = doc.page.height - 34;
    doc.moveTo(x, y - 6).lineTo(x + w, y - 6).lineWidth(0.5).strokeColor(RULE).stroke();
    doc.font(FONT).fontSize(7.5).fillColor(MUTED);
    doc.text(pdfText(`Keystone · ${spec.title} · ${stamp}`), x, y, { width: w * 0.75, lineBreak: false, ellipsis: true });
    doc.text(`${l.page} ${i - range.start + 1} / ${range.count}`, x, y, { width: w, align: 'right', lineBreak: false });
    doc.page.margins.bottom = keepBottom;
  }
}

function block(doc: Doc, b: PdfBlock, lang: Lang): void {
  const x = doc.page.margins.left;
  const w = contentWidth(doc);
  switch (b.kind) {
    case 'heading':
      ensure(doc, 40);
      doc.moveDown(0.4).font(BOLD).fontSize(11.5).fillColor(INK).text(pdfText(b.text), x, doc.y, { width: w });
      doc.moveDown(0.3);
      return;
    case 'paragraph':
      ensure(doc, 20);
      doc.font(FONT).fontSize(9.5).fillColor(b.muted ? MUTED : INK).text(pdfText(b.text), x, doc.y, { width: w, lineGap: 1.5 });
      doc.moveDown(0.5);
      return;
    case 'spacer':
      doc.y += b.height ?? 10;
      return;
    case 'pageBreak':
      doc.addPage();
      return;
    case 'fields': {
      const cols = b.columns ?? 2;
      const cw = w / cols;
      for (let i = 0; i < b.items.length; i += cols) {
        const row = b.items.slice(i, i + cols);
        const h = Math.max(...row.map(([label, value]) => doc.font(FONT).fontSize(7.5).heightOfString(pdfText(label), { width: cw - 10 }) + doc.font(FONT).fontSize(9.5).heightOfString(pdfText(value || '—'), { width: cw - 10 }))) + 8;
        ensure(doc, h);
        const y = doc.y;
        row.forEach(([label, value], j) => {
          doc.font(FONT).fontSize(7.5).fillColor(MUTED).text(pdfText(label.toUpperCase()), x + j * cw, y, { width: cw - 10 });
          doc.font(FONT).fontSize(9.5).fillColor(INK).text(pdfText(value || '—'), x + j * cw, doc.y + 1, { width: cw - 10 });
        });
        doc.y = y + h;
      }
      doc.x = x;
      doc.moveDown(0.3);
      return;
    }
    case 'kpis': {
      const n = Math.max(1, Math.min(5, b.items.length));
      const gap = 8;
      const tw = (w - gap * (n - 1)) / n;
      for (let i = 0; i < b.items.length; i += n) {
        ensure(doc, 58);
        const y = doc.y;
        b.items.slice(i, i + n).forEach((k, j) => {
          const tx = x + j * (tw + gap);
          doc.roundedRect(tx, y, tw, 50, 4).fillColor(FILL).fill();
          doc.font(FONT).fontSize(7).fillColor(MUTED).text(pdfText(k.label.toUpperCase()), tx + 8, y + 7, { width: tw - 16, lineBreak: false, ellipsis: true });
          doc.font(BOLD).fontSize(14).fillColor(INK).text(pdfText(k.value), tx + 8, y + 19, { width: tw - 16, lineBreak: false, ellipsis: true });
          if (k.sub) doc.font(FONT).fontSize(7).fillColor(MUTED).text(pdfText(k.sub), tx + 8, y + 37, { width: tw - 16, lineBreak: false, ellipsis: true });
        });
        doc.y = y + 58;
      }
      doc.x = x;
      return;
    }
    case 'table':
      table(doc, b.sheet.columns, b.sheet.rows, lang, b.totals);
      return;
    case 'signatures': {
      const n = Math.max(1, b.parties.length);
      const gap = 14;
      const bw = (w - gap * (n - 1)) / n;
      ensure(doc, 96);
      const y = doc.y + 4;
      b.parties.forEach((p, j) => {
        const bx = x + j * (bw + gap);
        doc.rect(bx, y, bw, 84).lineWidth(0.6).strokeColor(RULE).stroke();
        doc.font(BOLD).fontSize(8.5).fillColor(INK).text(pdfText(p.role), bx + 8, y + 7, { width: bw - 16 });
        if (p.name) doc.font(FONT).fontSize(8.5).fillColor(INK).text(pdfText(p.name), bx + 8, doc.y + 1, { width: bw - 16 });
        doc.font(FONT).fontSize(7.5).fillColor(MUTED).text(lang === 'fr' ? 'Date et signature' : 'Date and signature', bx + 8, y + 68, { width: bw - 16 });
      });
      doc.y = y + 96;
      doc.x = x;
      return;
    }
  }
}

function table(doc: Doc, columns: ExportColumn[], rows: Record<string, CellValue>[], lang: Lang, totals?: Record<string, CellValue>): void {
  const x = doc.page.margins.left;
  const w = contentWidth(doc);
  const rel = columns.map((c) => c.width ?? (isNumericType(c.type) || c.type === 'date' ? 10 : 18));
  const sum = rel.reduce((a, b) => a + b, 0) || 1;
  const widths = rel.map((r) => (r / sum) * w);
  const pad = 3;
  const fs = columns.length > 8 ? 7 : 8;
  const align = (c: ExportColumn) => c.align ?? (isNumericType(c.type) ? 'right' : 'left');

  const drawHeader = () => {
    const h = Math.max(...columns.map((c, i) => doc.font(BOLD).fontSize(fs).heightOfString(pdfText(c.header), { width: widths[i] - 2 * pad }))) + 2 * pad;
    const y = doc.y;
    doc.rect(x, y, w, h).fillColor(FILL).fill();
    let cx = x;
    columns.forEach((c, i) => {
      doc.font(BOLD).fontSize(fs).fillColor(INK).text(pdfText(c.header), cx + pad, y + pad, { width: widths[i] - 2 * pad, align: align(c) });
      cx += widths[i];
    });
    doc.y = y + h;
  };
  const drawRow = (r: Record<string, CellValue>, bold = false) => {
    const texts = columns.map((c) => pdfText(displayCell(r[c.key], c, lang)));
    const h = Math.max(fs + 2, ...texts.map((t, i) => doc.font(bold ? BOLD : FONT).fontSize(fs).heightOfString(t || ' ', { width: widths[i] - 2 * pad }))) + 2 * pad;
    if (doc.y + h > bottom(doc)) {
      doc.addPage();
      drawHeader();
    }
    const y = doc.y;
    let cx = x;
    texts.forEach((t, i) => {
      doc.font(bold ? BOLD : FONT).fontSize(fs).fillColor(INK).text(t, cx + pad, y + pad, { width: widths[i] - 2 * pad, align: align(columns[i]) });
      cx += widths[i];
    });
    doc.moveTo(x, y + h).lineTo(x + w, y + h).lineWidth(0.4).strokeColor(RULE).stroke();
    doc.y = y + h;
  };

  ensure(doc, 40);
  drawHeader();
  for (const r of rows) drawRow(r);
  if (totals) drawRow(totals, true);
  doc.x = x;
  doc.moveDown(0.6);
}
