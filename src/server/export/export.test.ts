// Export framework (chapter 4): CSV dialects, XLSX and PDF writers, the access rules of buildExportContext and the two
// reference providers (projects, budget) on a seeded in-memory database.
import { beforeAll, describe, expect, it } from 'vitest';
import { PERSONA_BY_ROLE } from '@/config/personas';
import { setDb } from '@/server/db/client';
import { openDatabase } from '@/server/db/open';
import { exportLog } from '@/server/db/schema';
import { getDb } from '@/server/db/client';
import { toCsv } from './csv';
import { renderPdf, pdfText } from './pdf';
import { ExportError, buildExportContext, exportFileName, logExport, runExport } from './run';
import { readXlsx, sheetName, toXlsx } from './xlsx';
import { pdfTextLines } from './test/pdf-text';
import type { ExportSheet } from './types';

const NOW = new Date('2026-10-09T08:00:00Z');
const ctxOf = (screen: string, role: keyof typeof PERSONA_BY_ROLE, query: string, lang: 'fr' | 'en' = 'en') =>
  buildExportContext({ screen, viewer: PERSONA_BY_ROLE[role], lang, params: new URLSearchParams(query), now: NOW });

const SHEET: ExportSheet = {
  name: 'Lines',
  columns: [
    { key: 'name', header: 'Name' }, { key: 'amount', header: 'Amount', type: 'money_keur' }, { key: 'rate', header: 'Rate', type: 'percent' },
    { key: 'due', header: 'Due', type: 'date' }, { key: 'ok', header: 'OK', type: 'boolean' }, { key: 'qty', header: 'Qty', type: 'number', decimals: 2 },
  ],
  rows: [
    { name: 'Steel; "S355"', amount: 1234.5, rate: 0.645, due: '2026-09-25', ok: true, qty: 2.5 },
    { name: '=HYPERLINK("x")', amount: -27, rate: null, due: null, ok: false, qty: 1000 },
  ],
};

describe('CSV writer', () => {
  it('English: comma separator, decimal point, BOM, quoting, formula guard', () => {
    expect(toCsv(SHEET, 'en')).toBe(
      '﻿Name,Amount,Rate,Due,OK,Qty\r\n"Steel; ""S355""",1234.5,64.5%,2026-09-25,Yes,2.5\r\n"\'=HYPERLINK(""x"")",-27,,,No,1000\r\n',
    );
  });
  it('French: semicolon separator and decimal comma', () => {
    expect(toCsv(SHEET, 'fr')).toBe(
      '﻿Name;Amount;Rate;Due;OK;Qty\r\n"Steel; ""S355""";1234,5;64,5%;2026-09-25;Oui;2,5\r\n\'=HYPERLINK("""x""");-27;;;Non;1000\r\n'.replace(
        '\'=HYPERLINK("""x""")',
        '"\'=HYPERLINK(""x"")"',
      ),
    );
  });
});

describe('XLSX writer', () => {
  it('writes real numbers and dates and reads them back', async () => {
    const bytes = await toXlsx({ title: 'Test', filters: ['Zone: EUNA'], sheets: [SHEET] }, {
      lang: 'fr', labels: { sheet: 'Export', title: 'Titre', project: 'Projet', filters: 'Filtres', exportedBy: 'Exporté par', exportedOn: 'Exporté le' },
      project: 'HLT-026 · Harbor Line', exportedBy: 'Marie Lefebvre', exportedOn: NOW,
    });
    expect(Buffer.from(bytes.subarray(0, 2)).toString('latin1')).toBe('PK');
    const sheets = await readXlsx(bytes);
    expect(sheets.map((s) => s.name)).toEqual(['Lines', 'Export']);
    expect(sheets[0].rows[0]).toEqual(['Name', 'Amount', 'Rate', 'Due', 'OK', 'Qty']);
    expect(sheets[0].rows[1]).toEqual(['Steel; "S355"', 1234.5, 0.645, '2026-09-25', true, 2.5]);
    expect(sheets[1].rows.map((r) => r[0])).toEqual(['Titre', 'Projet', 'Filtres', 'Exporté par', 'Exporté le']);
  });
  it('sheet names are valid and unique', () => {
    const taken = new Set<string>();
    expect([sheetName('Budget / cost: [EVM]', taken), sheetName('Budget / cost: [EVM]', taken), sheetName('x'.repeat(40), taken)]).toEqual([
      'Budget cost EVM', 'Budget cost EVM 2', 'x'.repeat(31),
    ]);
  });
});

describe('PDF writer', () => {
  it('maps text to the WinAnsi set of the standard fonts', () => {
    expect(pdfText('−€27k → ≥ 4\u202f800 k€ · « Réception » ✓ œ')).toBe('-€27k -> >= 4 800 k€ · « Réception » v œ');
    expect(pdfText('Ω')).toBe('?');
  });
  it('renders a branded, paginated document', async () => {
    const rows = Array.from({ length: 120 }, (_, i) => ({ name: `Line ${i + 1}`, amount: i * 10, rate: 0.5, due: '2026-09-25', ok: true, qty: i }));
    const pdf = await renderPdf({
      title: 'Purchase order PO-1082', subtitle: 'Halvorsen Cranes', project: { code: 'HLT-026', name: 'Harbor Line' }, reference: 'PO-1082', date: '2026-09-25',
      blocks: [
        { kind: 'kpis', items: [{ label: 'Total', value: '€4,700', sub: 'excl. VAT' }] },
        { kind: 'fields', items: [['Supplier', 'Halvorsen Cranes'], ['Incoterm', 'DAP Le Havre']] },
        { kind: 'heading', text: 'Lines' },
        { kind: 'table', sheet: { ...SHEET, rows }, totals: { name: 'Total', amount: 71400 } },
        { kind: 'signatures', parties: [{ role: 'Buyer', name: 'Fabien Bertrand' }, { role: 'Supplier' }] },
      ],
      footnote: 'Generated by Keystone.',
    }, 'en', NOW, { compress: false });
    expect(Buffer.from(pdf.subarray(0, 5)).toString('latin1')).toBe('%PDF-');
    const text = pdfTextLines(pdf).join('\n');
    expect(text).toContain('Purchase order PO-1082');
    expect(text).toContain('HLT-026 · Harbor Line');
    expect(text).toContain('Line 120');
    expect(text).toMatch(/Page 1 \/ [3-9]/);
    expect(text).toContain('€71.40M');
    expect(text).toContain('25 Sep 2026');
  });
});

describe('export context and reference providers (seeded database)', () => {
  beforeAll(async () => {
    setDb(await openDatabase());
  }, 60_000);

  it('access rules: unknown screen, missing / unknown project, client on another organisation', async () => {
    await expect(ctxOf('nope', 'director', '')).rejects.toMatchObject({ status: 404 });
    await expect(ctxOf('budget', 'director', '')).rejects.toMatchObject({ status: 400 });
    await expect(ctxOf('budget', 'director', 'code=XXX-999')).rejects.toMatchObject({ status: 404 });
    await expect(ctxOf('budget', 'client', 'code=NDC-031')).rejects.toBeInstanceOf(ExportError);
    // P-1: outside their workspace a client is refused (even on their own project); an internal role exports read-only.
    await expect(ctxOf('budget', 'client', 'code=HLT-026')).rejects.toMatchObject({ status: 403 });
    const c = await ctxOf('budget', 'quality', 'code=HLT-026&tab=setup&format=xlsx');
    expect([c.project?.code, c.outside, c.readOnly, c.ratesMasked, c.params.get('tab'), c.params.has('format')]).toEqual(['HLT-026', true, false, true, 'setup', false]);
    const pm = await ctxOf('budget', 'pm', 'code=NDC-031');
    expect([pm.readOnly, pm.ratesMasked, pm.outside]).toEqual([true, false, false]);
  });

  it('projects register: director sees every project, the client is refused (P-1); filters apply', async () => {
    const all = await runExport(await ctxOf('projects', 'director', ''), 'csv');
    const lines = new TextDecoder().decode(all.body).replace(/^﻿/, '').trim().split('\r\n');
    expect(all.rowCount).toBe(17);
    expect(lines[0]).toBe('Code,Project,Stage,Project manager,Client,Analytic code,Machine type,Start date,Finish,Health,SPI,CPI,Next milestone,Attention');
    // R-185: the machine type column gives the equipment lines (Harbor Line: its EMP and three MEMU).
    expect(lines[1].startsWith('HLT-026,Harbor Line Terminal Expansion,Fabrication & Assemblage,R. Aubert,Port authority,HAV004,1 × EMP · 3 × MEMU,2026-01,2026-12,')).toBe(true); // R-157: Start / Finish are month dates
    // P-1: the projects register is outside the client's workspace — refused (the provider still filters by organisation).
    await expect(ctxOf('projects', 'client', '')).rejects.toMatchObject({ status: 403 });
    const q = await runExport(await ctxOf('projects', 'director', 'q=harbor&view=budget'), 'xlsx');
    const [sheet] = await readXlsx(q.body);
    expect(sheet.rows.length).toBe(2);
    expect(sheet.rows[1].slice(0, 1).concat(sheet.rows[1].slice(9, 12))).toEqual(['HLT-026', 4800, 3360, 0.7]);
    expect(q.fileName).toBe('projects-2026-10-09.xlsx');
  });

  it('budget: Excel sheets per tab, CSV of the current tab, PDF report with the key figures', async () => {
    const x = await runExport(await ctxOf('budget', 'director', 'code=HLT-026&tab=setup'), 'xlsx');
    const sheets = await readXlsx(x.body);
    expect(sheets.map((s) => s.name)).toEqual(['Cost categories', 'Work packages', 'Changes', 'EVM', 'Export']);
    expect(sheets[0].rows[1].slice(0, 2)).toEqual(['C01', 'Labor']);
    expect(typeof sheets[0].rows[1][4]).toBe('number');
    expect(x.fileName).toBe('budget-HLT-026-2026-10-09.xlsx');
    const csvFile = await runExport(await ctxOf('budget', 'director', 'code=HLT-026', 'fr'), 'csv');
    expect([...csvFile.body.subarray(0, 3)]).toEqual([0xef, 0xbb, 0xbf]);
    // Delivery 7 (R-073, C-2a): the series are computed from the activities and BL1 (was the seeded 162 / 170 / 175).
    expect(new TextDecoder().decode(csvFile.body).split('\r\n').slice(0, 2)).toEqual(['Mois;PV;EV;AC', 'janv.;96;96;92']);
    const pdf = await runExport(await ctxOf('budget', 'director', 'code=HLT-026', 'fr'), 'pdf', { compressPdf: false });
    expect(Buffer.from(pdf.body.subarray(0, 4)).toString('latin1')).toBe('%PDF');
    const text = pdfTextLines(pdf.body).join('\n');
    expect(text).toContain('Budget et coûts');
    expect(text).toContain('Rapport de coûts');
    expect(text).toContain('HLT-026');
    expect(text).toContain('4 800 k€');
    await expect(runExport(await ctxOf('budget', 'director', 'code=EWA-051'), 'xlsx')).rejects.toMatchObject({ status: 404 });
    await expect(runExport(await ctxOf('projects', 'director', ''), 'pdf')).rejects.toMatchObject({ status: 404 });
  });

  it('file names and the export log', async () => {
    const c = await ctxOf('budget', 'director', 'code=HLT-026&variant=po&id=PO-1082');
    expect(exportFileName('po', c, 'pdf')).toBe('po-HLT-026-PO-1082-2026-10-09.pdf');
    const f = await runExport(await ctxOf('projects', 'director', 'status=chantier'), 'csv');
    await logExport(await ctxOf('projects', 'director', 'status=chantier'), f);
    const rows = await (await getDb()).select().from(exportLog);
    expect(rows.at(-1)).toMatchObject({ screen: 'projects', format: 'csv', byName: 'Marie Lefebvre', byRole: 'director', params: { status: 'chantier' }, rowCount: f.rowCount });
  });
});
